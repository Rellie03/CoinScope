export function catalogToIdentification(coin: CatalogCoin): Identification {
  const { image: _image, era: _era, region: _region, featured: _featured, ...ident } = coin;
  void _image;
  void _era;
  void _region;
  void _featured;
  return ident;
}

export function searchCatalog(query: string): CatalogCoin[] {
  const q = query.trim().toLowerCase();
  if (!q) return CATALOG;
  return CATALOG.filter((c) => {
    const hay = [
      c.name,
      c.shortName,
      c.country,
      c.year,
      c.denomination,
      c.metal,
      c.designer,
      c.variety,
      c.era,
      c.region,
      c.mint,
    ]
      .join(" ")
      .toLowerCase();
    return hay.includes(q);
  });
}

export function matchCatalogId(ident: Pick<Identification, "name" | "denomination" | "country" | "year">) {
  const hay = `${ident.name} ${ident.denomination} ${ident.country} ${ident.year}`.toLowerCase();
  let best: { id: string; score: number } | null = null;
  for (const coin of CATALOG) {
    const tokens = [coin.shortName, coin.name, coin.denomination, coin.id.replace(/-/g, " ")];
    const score = tokens.reduce((acc, t) => (hay.includes(t.toLowerCase()) ? acc + t.length : acc), 0);
    if (score > 6 && (!best || score > best.score)) best = { id: coin.id, score };
  }
  return best?.id ?? null;
}

